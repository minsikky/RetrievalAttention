#!/bin/bash
#SBATCH --job-name=gen-mem
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=1
#SBATCH --cpus-per-task=4
#SBATCH --mem=48000m
#SBATCH --time=120:00
#SBATCH --account=zhengya98
#SBATCH --partition=spgpu
#SBATCH --gpus-per-node=1

module purge
module load python/3.10.4
module unload pytorch 2>/dev/null || true
module load cuda/12.8.1

if [ -f ".venv/bin/activate" ]; then
  # shellcheck disable=SC1091
  source .venv/bin/activate
else
  echo "[ERROR] .venv/bin/activate not found."
  exit 1
fi

unset PYTHONPATH
unset PYTHONHOME
export PYTHONNOUSERSITE=1
export TOKENIZERS_PARALLELISM=false
set -euo pipefail

MODE="${ONLINE_MODE:-baseline}"
MODEL_NAME="${MODEL_NAME:-meta-llama/Llama-3.1-8B-Instruct}"
ATTN_TYPE="${ATTN_TYPE:-RetrievalAttention}"
NUM_SAMPLES="${NUM_SAMPLES:-1}"
NUM_ENTRIES="${NUM_ENTRIES:-48}"
NUM_QUERIES="${NUM_QUERIES:-4}"
MAX_NEW_TOKENS="${MAX_NEW_TOKENS:-0}"
TOKEN_BUDGET_OVERRIDE="${TOKEN_BUDGET_OVERRIDE:-100}"
OUTPUT_DIR="${OUTPUT_DIR:-generated_memory_eval_result}"
DTYPE="${DTYPE:-bf16}"
BATCH_SIZE="${BATCH_SIZE:-1}"
PREFILL_FILLER_REPEATS="${PREFILL_FILLER_REPEATS:-0}"
MIN_PROMPT_TOKENS="${MIN_PROMPT_TOKENS:-0}"

case "${MODE}" in
  baseline)
    export RETRIEVALATTN_ONLINE_DYNAMIC_RANGE=0
    export RETRIEVALATTN_ONLINE_GRAPH_ENABLE=0
    export RETRIEVALATTN_GROW_STATIC_SUFFIX=0
    ;;
  dynamic)
    export RETRIEVALATTN_ONLINE_DYNAMIC_RANGE=1
    export RETRIEVALATTN_ONLINE_GRAPH_ENABLE=0
    export RETRIEVALATTN_GROW_STATIC_SUFFIX=0
    ;;
  online)
    export RETRIEVALATTN_ONLINE_DYNAMIC_RANGE=1
    export RETRIEVALATTN_ONLINE_GRAPH_ENABLE=1
    export RETRIEVALATTN_GROW_STATIC_SUFFIX=0
    ;;
  growing_static)
    export RETRIEVALATTN_ONLINE_DYNAMIC_RANGE=0
    export RETRIEVALATTN_ONLINE_GRAPH_ENABLE=0
    export RETRIEVALATTN_GROW_STATIC_SUFFIX=1
    ;;
  full_dense)
    export RETRIEVALATTN_ONLINE_DYNAMIC_RANGE=0
    export RETRIEVALATTN_ONLINE_GRAPH_ENABLE=0
    export RETRIEVALATTN_GROW_STATIC_SUFFIX=0
    ATTN_TYPE="Full_Flash_Attn"
    ;;
  *)
    echo "[ERROR] Unknown ONLINE_MODE=${MODE}. Use baseline|dynamic|online|growing_static|full_dense."
    exit 2
    ;;
esac

export RETRIEVALATTN_ONLINE_GRAPH_BIDIR="${RETRIEVALATTN_ONLINE_GRAPH_BIDIR:-1}"
export RETRIEVALATTN_ONLINE_GRAPH_INSERT_K="${RETRIEVALATTN_ONLINE_GRAPH_INSERT_K:-8}"
export RETRIEVALATTN_ONLINE_GRAPH_NEIGHBOR_CAP="${RETRIEVALATTN_ONLINE_GRAPH_NEIGHBOR_CAP:-16}"
export RETRIEVALATTN_ONLINE_GRAPH_DEFER="${RETRIEVALATTN_ONLINE_GRAPH_DEFER:--1}"
export RETRIEVALATTN_ONLINE_GRAPH_LOG="${RETRIEVALATTN_ONLINE_GRAPH_LOG:-1}"

export RETRIEVALATTN_DECODE_BACKEND="${RETRIEVALATTN_DECODE_BACKEND:-roar_cuda_fullgpu}"
export RETRIEVALATTN_DECODE_PROFILE="${RETRIEVALATTN_DECODE_PROFILE:-1}"
export RETRIEVALATTN_DECODE_INDEX="${RETRIEVALATTN_DECODE_INDEX:-faiss}"
export RETRIEVALATTN_SEED_MODE="${RETRIEVALATTN_SEED_MODE:-graph_only}"
export RETRIEVALATTN_QUERY_MODE="${RETRIEVALATTN_QUERY_MODE:-per_head}"
export RETRIEVALATTN_SCORE_MODE="${RETRIEVALATTN_SCORE_MODE:-ip}"
export RETRIEVALATTN_GRAPH_EXPAND="${RETRIEVALATTN_GRAPH_EXPAND:-1}"
export RETRIEVALATTN_EXPAND_WIDTH="${RETRIEVALATTN_EXPAND_WIDTH:-48}"
export RETRIEVALATTN_MIN_VISITS="${RETRIEVALATTN_MIN_VISITS:-96}"
export RETRIEVALATTN_MAX_VISITS="${RETRIEVALATTN_MAX_VISITS:-2048}"
export RETRIEVALATTN_STOP_PATIENCE="${RETRIEVALATTN_STOP_PATIENCE:-1}"
export RETRIEVALATTN_STOP_MARGIN="${RETRIEVALATTN_STOP_MARGIN:-0.001}"
export RETRIEVALATTN_SEED_PREV_K="${RETRIEVALATTN_SEED_PREV_K:-256}"
export RETRIEVALATTN_SEED_HUB_K="${RETRIEVALATTN_SEED_HUB_K:-64}"
export RETRIEVALATTN_SEED_TAIL_K="${RETRIEVALATTN_SEED_TAIL_K:-32}"
export RETRIEVALATTN_FA_FUSED_PREFILL=1
export RETRIEVALATTN_FA_GRAPH_FUSED="${RETRIEVALATTN_FA_GRAPH_FUSED:-1}"
export RETRIEVALATTN_ROAR_BACKEND="${RETRIEVALATTN_ROAR_BACKEND:-cpp}"

echo "[INFO] Job started at: $(date)"
echo "[INFO] Host: $(hostname)"
echo "[INFO] ONLINE_MODE=${MODE}"
echo "[INFO] ATTN_TYPE=${ATTN_TYPE}"
echo "[INFO] MODEL_NAME=${MODEL_NAME}"
echo "[INFO] NUM_SAMPLES=${NUM_SAMPLES}"
echo "[INFO] NUM_ENTRIES=${NUM_ENTRIES}"
echo "[INFO] NUM_QUERIES=${NUM_QUERIES}"
echo "[INFO] MAX_NEW_TOKENS=${MAX_NEW_TOKENS}"
echo "[INFO] TOKEN_BUDGET_OVERRIDE=${TOKEN_BUDGET_OVERRIDE}"
echo "[INFO] RETRIEVALATTN_DECODE_BACKEND=${RETRIEVALATTN_DECODE_BACKEND}"
echo "[INFO] RETRIEVALATTN_ONLINE_DYNAMIC_RANGE=${RETRIEVALATTN_ONLINE_DYNAMIC_RANGE}"
echo "[INFO] RETRIEVALATTN_ONLINE_GRAPH_ENABLE=${RETRIEVALATTN_ONLINE_GRAPH_ENABLE}"
echo "[INFO] RETRIEVALATTN_GROW_STATIC_SUFFIX=${RETRIEVALATTN_GROW_STATIC_SUFFIX}"
echo "[INFO] RETRIEVALATTN_ONLINE_GRAPH_INSERT_K=${RETRIEVALATTN_ONLINE_GRAPH_INSERT_K}"
echo "[INFO] RETRIEVALATTN_ONLINE_GRAPH_DEFER=${RETRIEVALATTN_ONLINE_GRAPH_DEFER}"
echo "[INFO] MIN_PROMPT_TOKENS=${MIN_PROMPT_TOKENS}"

python benchmark/generated_memory_eval.py \
  --model_name "${MODEL_NAME}" \
  --attn_type "${ATTN_TYPE}" \
  --dtype "${DTYPE}" \
  --batch_size "${BATCH_SIZE}" \
  --num_samples "${NUM_SAMPLES}" \
  --num_entries "${NUM_ENTRIES}" \
  --num_queries "${NUM_QUERIES}" \
  --max_new_tokens "${MAX_NEW_TOKENS}" \
  --token_budget_override "${TOKEN_BUDGET_OVERRIDE}" \
  --prefill_filler_repeats "${PREFILL_FILLER_REPEATS}" \
  --min_prompt_tokens "${MIN_PROMPT_TOKENS}" \
  --output_dir "${OUTPUT_DIR}"
